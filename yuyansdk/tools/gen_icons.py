"""Generate Android vector drawables for the Threebrook Input icon, following the
Threebrook product icon family (G:/Projects/Threebrook Seek/tools/branding/brand/design/Icons.dc.html):
rounded square (radius = 22% of side), top-light/bottom-dark product colour, white main glyph,
the 'moon over three brooks' signature in the bottom-left. Product colour: 晴蓝 #2F7FC1.

VectorDrawable has no SVG mask, so wave cut-outs are built as even-odd holes:
clip to the moon circle, then fill (bounding square + wave bands) with evenOdd."""
import math
import os
import sys

OUT = sys.argv[1]
TOP, BASE, BOTTOM = "#3C8FD6", "#2F7FC1", "#2A6FB0"  # 晴蓝 gradient, as gBlue in the brand Icons.dc.html
SIGN_ALPHA = "0.72"


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def rounded_rect(x, y, w, h, r):
    return (f"M{f(x + r)},{f(y)} H{f(x + w - r)} A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)} V{f(y + h - r)} "
            f"A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)} H{f(x + r)} A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)} "
            f"V{f(y + r)} A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)} Z")


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)} A{f(r)},{f(r)} 0 1 1 {f(cx + r)},{f(cy)} A{f(r)},{f(r)} 0 1 1 {f(cx - r)},{f(cy)} Z"


def wave_band(y0, x_from, x_to, period, amp, thickness, sx, sy, ox, oy):
    """Band of the given thickness around y = y0 + amp*sin-like quadratic wave (same shape as
    'M.. Q.. T..' in the design: quadratic segments of half a period, alternating up/down)."""
    pts = []
    n = int((x_to - x_from) / period * 2 * 16) + 1
    for i in range(n + 1):
        x = x_from + (x_to - x_from) * i / n
        t = ((x - x_from) / (period / 2)) % 2  # 0..2 over one full period
        seg, u = (0, t) if t < 1 else (1, t - 1)
        bump = 4 * u * (1 - u) * amp  # quadratic bezier with control at -2*amp gives peak amp
        y = y0 - bump if seg == 0 else y0 + bump
        pts.append((x, y))
    upper = [(x, y - thickness / 2) for x, y in pts]
    lower = [(x, y + thickness / 2) for x, y in reversed(pts)]
    poly = upper + lower
    return "M" + " L".join(f"{f(ox + x * sx)},{f(oy + y * sy)}" for x, y in poly) + " Z"


def moon(cx, cy, r, waves, period, amp, thickness):
    """Moon signature in absolute coords: returns (clip path, evenOdd fill path).
    waves: list of y offsets relative to moon centre, in units of r."""
    clip = circle(cx, cy, r)
    square = f"M{f(cx - r)},{f(cy - r)} H{f(cx + r)} V{f(cy + r)} H{f(cx - r)} Z"
    bands = [wave_band(cy + w * r, cx - r * 1.3, cx + r * 1.3, period * r, amp * r, thickness * r, 1, 1, 0, 0)
             for w in waves]
    return clip, " ".join([square] + bands)


# moon proportions from markB (viewBox 100: circle r40 at 50,50; waves at y 58 & 74, stroke 7, period 24, amp 4)
BIG_MOON = dict(waves=[8 / 40, 24 / 40], period=24 / 40, amp=4 / 40, thickness=7 / 40)
# small-size version: 'moon slightly bigger, two thicker waves'
SMALL_MOON = dict(waves=[6 / 40, 24 / 40], period=30 / 40, amp=4.5 / 40, thickness=10 / 40)


def keyboard(x, y, w, h):
    """White keyboard glyph with key holes (evenOdd). Layout designed on a 152x96 body."""
    s = w / 152
    r = 18 * s
    parts = [rounded_rect(x, y, w, h, r)]
    key, gap, kr = 20 * s, 7 * s, 4.5 * s
    inner_x = x + 12 * s
    for i in range(5):  # row 1: 5 keys
        parts.append(rounded_rect(inner_x + i * (key + gap), y + 14 * s, key, 18 * s, kr))
    row2_x = inner_x + (key + gap) / 2
    for i in range(4):  # row 2: 4 keys, offset half a key
        parts.append(rounded_rect(row2_x + i * (key + gap), y + 40 * s, key, 18 * s, kr))
    parts.append(rounded_rect(x + 34 * s, y + 66 * s, w - 68 * s, 16 * s, kr))  # space bar
    return " ".join(parts)


def gradient(start_y, end_y, attr):
    return f"""        <aapt:attr name="{attr}">
            <gradient android:type="linear" android:startX="0" android:startY="{f(start_y)}" android:endX="0" android:endY="{f(end_y)}">
                <item android:offset="0" android:color="{TOP}"/>
                <item android:offset="1" android:color="{BOTTOM}"/>
            </gradient>
        </aapt:attr>"""


def vector(size_dp, viewport, body, aapt=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_icons.py (python tools/gen_icons.py src/main/res) from the Threebrook product icon family. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}
    android:width="{size_dp}dp" android:height="{size_dp}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
{body}
</vector>
"""


def moon_group(cx, cy, r, color, alpha, spec):
    clip, fill = moon(cx, cy, r, **spec)
    return f"""    <group>
        <clip-path android:pathData="{clip}"/>
        <path android:fillType="evenOdd" android:fillColor="{color}" android:fillAlpha="{alpha}" android:pathData="{fill}"/>
    </group>"""


def full_icon(gradient_fill):
    """Rounded-square icon in the 256 design grid (legacy launchers, in-app use)."""
    if gradient_fill:
        bg = f"""    <path android:pathData="{rounded_rect(8, 8, 240, 240, 54)}">
{gradient(8, 248, "android:fillColor")}
    </path>"""
    else:
        bg = f'    <path android:fillColor="{BASE}" android:pathData="{rounded_rect(8, 8, 240, 240, 54)}"/>'
    kb = f'    <path android:fillType="evenOdd" android:fillColor="#FFFFFF" android:pathData="{keyboard(52, 64, 152, 96)}"/>'
    sign = moon_group(26 + 35, 172 + 35, 28, "#FFFFFF", SIGN_ALPHA, BIG_MOON)
    return vector(108, 256, "\n".join([bg, kb, sign]), aapt=gradient_fill)


def adaptive_background():
    body = f"""    <path android:pathData="M0,0 H108 V108 H0 Z">
{gradient(0, 108, "android:fillColor")}
    </path>"""
    return vector(108, 108, body, aapt=True)


def adaptive_foreground(color="#FFFFFF", sign_alpha=SIGN_ALPHA):
    # everything inside the 66dp safe circle (centre 54,54 r 33) so any launcher mask keeps it whole
    kb = f'    <path android:fillType="evenOdd" android:fillColor="{color}" android:pathData="{keyboard(31, 31, 46, 29.05)}"/>'
    sign = moon_group(37.5, 71, 8.5, color, sign_alpha, BIG_MOON)
    return vector(108, 108, "\n".join([kb, sign]))


def toolbar_mark():
    """Small mark for the keyboard toolbar and notifications: tinted at runtime, so plain black fill."""
    return vector(35, 48, moon_group(24, 24, 19, "#000000", "1", SMALL_MOON))


def adaptive_icon():
    return """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""


files = {
    "drawable/ic_sdk_launcher.xml": full_icon(False),
    "drawable-v24/ic_sdk_launcher.xml": full_icon(True),
    "drawable-anydpi-v26/ic_sdk_launcher.xml": adaptive_icon(),
    "drawable/ic_launcher_background.xml": adaptive_background(),
    "drawable/ic_launcher_foreground.xml": adaptive_foreground(),
    "drawable/ic_launcher_monochrome.xml": adaptive_foreground("#000000", "1"),
    "drawable/ic_sdk_launcher_transparent.xml": toolbar_mark(),
}
for rel, text in files.items():
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fp:
        fp.write(text)
    print(rel, len(text))
